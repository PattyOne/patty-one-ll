create table public.ordens_producao (
  id uuid primary key default gen_random_uuid(),
  numero bigint generated by default as identity unique,
  tipo text not null check (tipo in ('Instalação', 'Impressão')),
  status text not null default 'Aguardando' check (status in ('Aguardando', 'Em andamento', 'Concluída', 'Cancelada')),
  prioridade text not null default 'Normal' check (prioridade in ('Baixa', 'Normal', 'Alta', 'Urgente')),
  venda_id uuid references public.vendas(id) on delete set null,
  cadastro_id uuid references public.cadastros(id) on delete set null,
  servico_id uuid references public.producao_servicos(id) on delete set null,
  descricao text not null,
  data_prevista date,
  data_inicio timestamptz,
  data_conclusao timestamptz,
  local_instalacao text,
  veiculo_id uuid references public.producao_veiculos(id) on delete set null,
  observacao text,
  created_by uuid references public.profiles(id) default auth.uid(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index ordens_producao_status_idx on public.ordens_producao(status);
create index ordens_producao_tipo_idx on public.ordens_producao(tipo);
create index ordens_producao_previsao_idx on public.ordens_producao(data_prevista);
create index ordens_producao_venda_idx on public.ordens_producao(venda_id);
grant select, insert, update, delete on public.ordens_producao to authenticated;
grant all on public.ordens_producao to service_role;
alter table public.ordens_producao enable row level security;
create policy "ordens_producao_select" on public.ordens_producao for select to authenticated using (public.is_membro(auth.uid()));
create policy "ordens_producao_insert" on public.ordens_producao for insert to authenticated with check (public.is_membro(auth.uid()));
create policy "ordens_producao_update" on public.ordens_producao for update to authenticated using (public.is_membro(auth.uid())) with check (public.is_membro(auth.uid()));
create policy "ordens_producao_delete" on public.ordens_producao for delete to authenticated using (public.has_role(auth.uid(), 'admin'));
create trigger ordens_producao_touch before update on public.ordens_producao for each row execute function public.touch_updated_at();

create table public.ordens_producao_equipe (
